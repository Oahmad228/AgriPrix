"""Derive one lock file per service from requirements.lock (ADR-008 debt, Sprint 4).

Each service lists its top-level packages; the script walks their declared dependencies
(importlib.metadata, markers evaluated for this Python/platform, extras followed only when
listed) and writes the closure with the exact versions of requirements.lock. Nothing is
re-resolved, so every service runs the same versions as the tested development image.

Run inside the job-runner (where the full lock is installed):
    python tools/split_lock.py
"""

from __future__ import annotations

import re
import sys
from importlib import metadata
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[1]
FULL_LOCK = ROOT / "requirements.lock"
OUT_DIR = ROOT / "requirements"

SERVICES: dict[str, list[str]] = {
    # FastAPI + read-only SQL; uvicorn[standard] extras for the production server.
    "api": ["fastapi", "uvicorn[standard]", "pydantic-settings", "sqlalchemy", "psycopg[binary]",
            "slowapi", "httpx"],
    # Streamlit UI: talks HTTP only, no SQL driver (EF-13).
    "dashboard": ["streamlit", "plotly", "httpx", "pydantic-settings"],
    # MLflow tracking server with its PostgreSQL backend.
    "mlflow": ["mlflow", "psycopg2-binary", "sqlalchemy"],
    # ETL, training, anomalies, reports and the monthly scheduler: everything but dev tools.
    "jobs": ["pandas", "numpy", "scikit-learn", "lightgbm", "statsmodels", "scipy", "matplotlib",
             "mlflow", "sqlalchemy", "psycopg[binary]", "httpx", "pydantic-settings", "fastapi"],
}  # fmt: skip


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def pinned() -> dict[str, str]:
    lines = FULL_LOCK.read_text(encoding="utf-8").splitlines()
    pins = {}
    for line in lines:
        line = line.strip()
        if line and not line.startswith("#"):
            name, version = line.split("==")
            pins[canonical(name)] = f"{name}=={version}"
    return pins


def closure(roots: list[str]) -> set[str]:
    env = default_environment()
    seen: set[str] = set()
    stack = [Requirement(r) for r in roots]
    while stack:
        req = stack.pop()
        key = canonical(req.name)
        extras = set(req.extras)
        marker_key = (key, frozenset(extras))
        if marker_key in seen:
            continue
        seen.add(marker_key)
        dist = metadata.distribution(req.name)
        for raw in dist.requires or []:
            child = Requirement(raw)
            if child.marker is None:
                stack.append(child)
                continue
            # Base requirement, or one gated by an extra we asked for.
            if any(child.marker.evaluate(env | {"extra": e}) for e in (extras or {""})):
                stack.append(child)
    return {name for name, _ in seen}


def main() -> int:
    pins = pinned()
    OUT_DIR.mkdir(exist_ok=True)
    for service, roots in SERVICES.items():
        names = closure(roots)
        missing = sorted(n for n in names if n not in pins)
        if missing:
            print(f"{service}: not in requirements.lock: {missing}", file=sys.stderr)
            return 1
        lines = sorted((pins[n] for n in names), key=str.lower)
        header = (
            f"# {service} image dependencies: subset of requirements.lock, generated by\n"
            "# tools/split_lock.py (do not edit by hand). Installed with --no-deps + pip check.\n"
        )
        (OUT_DIR / f"{service}.lock").write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
        print(f"{service}: {len(lines)} packages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
